/**
 * Writes src/version.ts from package.json and the installed orz-markdown, so
 * the isomorphic modules know the shell version and the kit version the
 * build bundles without reading files (FC-18 law 2: no environment reads).
 * Run by `prebuild` and `pretest`; tests/lib.test.ts checks it is in sync.
 *
 * `ORZ_MARKDOWN_VERSION` is fixed at build time on purpose: the browser
 * bundle embeds the kit this build resolves, and the Node library must write
 * the same bytes (the theme URL names that kit) even when an installation
 * later resolves a newer orz-markdown under the `^` range (1.0.2).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { VERSION as KIT } from 'orz-markdown/version';

const { version } = JSON.parse(readFileSync('package.json', 'utf8')) as { version: string };
const out = [
  '// Generated by scripts/sync-version.ts from package.json and the installed orz-markdown — do not edit.',
  '',
  '/** The orz-mdhtml version: the shell version written into every assembled file. */',
  `export const VERSION = ${JSON.stringify(version)};`,
  '/**',
  ' * The orz-markdown version this release bundles (fixed at build time): the',
  ' * version its browser engine embeds and the one the theme URLs of every',
  ' * assembled file name, in Node and in the browser alike — not the kit an',
  ' * installation happens to resolve.',
  ' */',
  `export const ORZ_MARKDOWN_VERSION = ${JSON.stringify(KIT)};`,
  '',
].join('\n');
let current = '';
try {
  current = readFileSync('src/version.ts', 'utf8');
} catch {
  /* first run */
}
if (current !== out) writeFileSync('src/version.ts', out, 'utf8');
